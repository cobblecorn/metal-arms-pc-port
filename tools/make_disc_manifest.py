#!/usr/bin/env python3
"""Write port/setup/disc_manifest.h: the name, size and CRC32 of every file on the retail disc.

ma_setup checks each file it extracts against this list, so a player's own disc is accepted only
when it matches the USA GameCube release the port was built and tested with. The header holds
checksums only, no game data.

    python tools/make_disc_manifest.py [--data gamedata]
"""
import argparse
import pathlib
import struct
import zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def fst_files(fst):
    """(path, disc offset, size) for every file in a GameCube FST."""
    count = struct.unpack('>I', fst[8:12])[0]
    strings = count * 12

    def name(offset):
        end = fst.index(b'\0', strings + offset)
        return fst[strings + offset:end].decode('latin-1')

    files, dirs = [], [(count, '')]
    for i in range(1, count):
        word, a, b = struct.unpack('>III', fst[i * 12:i * 12 + 12])
        while dirs and i >= dirs[-1][0]:
            dirs.pop()
        prefix = dirs[-1][1] if dirs else ''
        if word >> 24:
            dirs.append((b, prefix + name(word & 0xFFFFFF) + '/'))
        else:
            files.append((prefix + name(word & 0xFFFFFF), a, b))
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--data', type=pathlib.Path, default=ROOT / 'gamedata',
                        help='extracted disc (sys/ and files/)')
    parser.add_argument('--out', type=pathlib.Path, default=ROOT / 'port/setup/disc_manifest.h')
    args = parser.parse_args()

    boot = (args.data / 'sys/boot.bin').read_bytes()
    game_id = boot[:6].decode('ascii')
    files = fst_files((args.data / 'sys/fst.bin').read_bytes())

    lines = [
        '// Generated by tools/make_disc_manifest.py from the retail USA GameCube disc. Checksums only.',
        '#pragma once',
        '',
        f'#define DISC_GAME_ID "{game_id}"',
        f'#define DISC_FILE_COUNT {len(files)}',
        '',
        'struct DiscManifestFile { const char *pszPath; unsigned int nSize; unsigned int nCrc; };',
        '',
        'static const DiscManifestFile Disc_aFiles[DISC_FILE_COUNT] = {',
    ]
    total = 0
    for path, _offset, size in files:
        data_path = args.data / 'files' / path
        if data_path.stat().st_size != size:
            raise SystemExit(f'{path}: extracted size differs from the disc FST')
        crc = 0
        with data_path.open('rb') as handle:
            while chunk := handle.read(1 << 22):
                crc = zlib.crc32(chunk, crc)
        total += size
        lines.append(f'\t{{ "{path}", {size}u, 0x{crc:08X}u }},')
    lines += ['};', '', f'#define DISC_TOTAL_BYTES {total}ull', '']
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text('\n'.join(lines), newline='\n')
    print(f'{args.out}: {game_id}, {len(files)} files, {total / 2**30:.2f} GiB')


if __name__ == '__main__':
    main()
