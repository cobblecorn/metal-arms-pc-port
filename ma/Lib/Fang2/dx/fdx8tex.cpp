		FDX8_pDev->SetTextureStageState( nStageNum, D3DTSS_ADDRESSW, _aDXTexAddress[!(_aSetTexState[nStageNum].TexInst.GetFlags() & CFTexInst::FLAG_WRAP_U)] );
