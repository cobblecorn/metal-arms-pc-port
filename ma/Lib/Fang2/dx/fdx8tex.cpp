FTexDef_t *ftex_Find( cchar *pszName ) 
{
	FTexData_t *pTexData;

	FASSERT( _bModuleInitialized );

	pTexData = (FTexData_t *)fres_FindBase( FTEX_RESNAME, pszName );

	if( pTexData ) 
	{
		return &pTexData->TexDef;
	}

	return NULL;
}


