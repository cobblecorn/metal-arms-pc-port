BOOL ftex_IsPointerValid( const FTexDef_t *pTexDef, BOOL bNullPointerIsValid ) 
{
	FASSERT( _bModuleInitialized );

	if( pTexDef == NULL ) 
	{
		return bNullPointerIsValid;
	}

	return (fres_FindHandle( pTexDef->pTexData ) != FRES_NULLHANDLE);
}


